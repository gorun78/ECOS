package com.chinacreator.gzcm.cli.commands;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.chinacreator.gzcm.cli.CliCommand;
import com.chinacreator.gzcm.cli.CliCommands;
import com.chinacreator.gzcm.cli.CliOptions;
import com.chinacreator.gzcm.cli.HttpTransport;
import com.chinacreator.gzcm.cli.OperationRegistry;
import com.sun.net.httpserver.HttpServer;
import java.io.OutputStream;
import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Map;
import java.util.concurrent.atomic.AtomicReference;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * 写命令重试安全性门禁：<b>自动生成的幂等键不得授权自动重试</b>。
 *
 * <p>背景（实测 2026-11-11）：{@code createCandidate} 每次都 {@code UUID.randomUUID()} 建新行，
 * 服务端<b>没有</b>按 {@code Idempotency-Key} 去重（全仓仅 {@code startRun} 有幂等通道）。
 * 而 CLI 此前把「有键」等同于「可重试」，键又是缺省自动生成的 ⇒ 响应丢失后重试会
 * <b>重复落库</b>。计划原文是「写命令默认不重试（除非带幂等键）」，指调用方显式声明。
 *
 * <p>本门禁钉三条：①缺省自动键 ⇒ 只发 1 次；②显式 {@code --idempotency-key} ⇒ 允许重试；
 * ③两条路径都必须真的把 {@code Idempotency-Key} 头发出去（键的作用是回显与人工重放，
 * 不能因为不重试就不发）。</p>
 */
class WriteRetrySafetyTest {

    private HttpServer server;
    private String baseUrl;
    private final List<String> keys = Collections.synchronizedList(new ArrayList<>());
    private final AtomicReference<Integer> attempts = new AtomicReference<>(0);

    @BeforeEach
    void setUp() throws Exception {
        server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        server.createContext("/api/v1/wagent/candidates", exchange -> {
            attempts.set(attempts.get() + 1);
            keys.add(String.valueOf(exchange.getRequestHeaders().getFirst("Idempotency-Key")));
            exchange.getRequestBody().readAllBytes();
            // 恒 503：可重试类别，用来观察重试次数
            byte[] bytes = "{\"code\":503,\"errorCode\":\"E-WA-DEP\",\"message\":\"dep down\"}"
                    .getBytes(StandardCharsets.UTF_8);
            exchange.getResponseHeaders().add("Content-Type", "application/json");
            exchange.sendResponseHeaders(503, bytes.length);
            try (OutputStream os = exchange.getResponseBody()) {
                os.write(bytes);
            }
        });
        server.start();
        baseUrl = "http://127.0.0.1:" + server.getAddress().getPort();
    }

    @AfterEach
    void tearDown() {
        server.stop(0);
    }

    private Map<String, Object> runExtract(String... extra) {
        List<String> argv = new ArrayList<>(List.of("knowledge", "extract",
                "--candidate-type", "KNOWLEDGE_ITEM", "--payload-json", "{}",
                "--base-url", baseUrl, "--token", "t"));
        argv.addAll(List.of(extra));
        CliOptions options = CliOptions.parse(argv.toArray(new String[0]), 2);
        CliCommand command = CliCommands.find(CliCommands.KNOWLEDGE_EXTRACT);
        assertNotNull(command);
        HttpTransport transport = new HttpTransport(options.baseUrl(), options.traceId(),
                options.timeoutMs(), options.retryPolicy(), true);
        return GenericCommandRunner.run(OperationRegistry.load(), options, transport, command);
    }

    @Test
    @DisplayName("缺省自动幂等键：只发 1 次（不得拿自动键当重试依据，否则重复落库）")
    void autoGeneratedKeyDoesNotAuthorizeRetry() {
        attempts.set(0);
        keys.clear();
        Map<String, Object> out = runExtract();
        assertEquals(1, attempts.get(),
                "缺省自动键不得授权自动重试；实际请求次数 " + attempts.get() + "，键=" + keys);
        assertTrue(String.valueOf(out.get("status")).equals("UNAVAILABLE")
                        || String.valueOf(out.get("status")).equals("FAILED"),
                "503 应如实报不可用/失败，实得 " + out.get("status"));
        // 键仍必须发出（回显 + 人工重放要用），且只发一次
        assertEquals(1, keys.size());
        assertTrue(String.valueOf(keys.get(0)).startsWith("cli-"), "缺省键应 cli-<uuid>，实得 " + keys.get(0));
    }

    @Test
    @DisplayName("显式 --idempotency-key：允许按策略重试，且每次都用同一个键（服务端据此去重）")
    void explicitKeyAuthorizesRetryWithSameKey() {
        attempts.set(0);
        keys.clear();
        runExtract("--idempotency-key", "run-abc-1");
        assertTrue(attempts.get() > 1,
                "显式键应允许重试（503 可恢复），实际请求次数 " + attempts.get());
        for (String k : keys) {
            assertEquals("run-abc-1", k, "重试必须复用同一键，否则服务端无法去重: " + keys);
        }
    }
}
